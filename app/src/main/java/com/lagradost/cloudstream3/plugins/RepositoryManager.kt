/**
 * Comes with the app, always available in the app, non removable.
 */
@Serializable
data class Repository(
    @JsonProperty("iconUrl") @SerialName("iconUrl") val iconUrl: String?,
    @JsonProperty("name") @SerialName("name") val name: String,
    @JsonProperty("description") @SerialName("description") val description: String?,
    @JsonProperty("manifestVersion") @SerialName("manifestVersion") val manifestVersion: Int,
    @JsonProperty("pluginLists") @SerialName("pluginLists") val pluginLists: List<String>,
)

/**
 * Status int as the following:
 * 0: Down
 * 1: Ok
 * 2: Slow
 * 3: Beta only
 */
@Serializable
data class SitePlugin(
    // Url to the .cs3 file
    @JsonProperty("url") @SerialName("url") val url: String,
    // Status to remotely disable the provider
    @JsonProperty("status") @SerialName("status") val status: Int,
    // Integer over 0, any change of this will trigger an auto update
    @JsonProperty("version") @SerialName("version") val version: Int,
    // Unused currently, used to make the api backwards compatible?
    // Set to 1
    @JsonProperty("apiVersion") @SerialName("apiVersion") val apiVersion: Int,
    // Name to be shown in app
    @JsonProperty("name") @SerialName("name") val name: String,
    // Name to be referenced internally. Separate to make name and url changes possible
    @JsonProperty("internalName") @SerialName("internalName") val internalName: String,
    @JsonProperty("authors") @SerialName("authors") val authors: List<String>,
    @JsonProperty("description") @SerialName("description") val description: String?,
    // Might be used to go directly to the plugin repo in the future
    @JsonProperty("repositoryUrl") @SerialName("repositoryUrl") val repositoryUrl: String?,
    // These types are yet to be mapped and used, ignore for now
    @JsonProperty("tvTypes") @SerialName("tvTypes") val tvTypes: List<String>?,
    // Most often a language tag like "en" or "zh-TW"
    @JsonProperty("language") @SerialName("language") val language: String?,
    @JsonProperty("iconUrl") @SerialName("iconUrl") val iconUrl: String?,
    // Automatically generated by the gradle plugin
    @JsonProperty("fileSize") @SerialName("fileSize") val fileSize: Long?,
    @JsonProperty("fileHash") @SerialName("fileHash") val fileHash: String?,
)

@Serializable
data class PluginWrapper(
    @JsonProperty("repository") @SerialName("repository") val repository: Repository,
    @JsonProperty("repositoryData") @SerialName("repositoryData") val repositoryData: RepositoryData,
    @JsonProperty("plugin") @SerialName("plugin") val plugin: SitePlugin
) {
    companion object {
        private val localRepository = Repository("", "", "", 1, emptyList())
        private val localRepositoryData = RepositoryData("", "", "")
        fun getLocalPluginWrapper(plugin: SitePlugin): PluginWrapper {
            return PluginWrapper(
                localRepository,
                localRepositoryData,
                plugin
            )
        }
    }
}


object RepositoryManager {
    const val ONLINE_PLUGINS_FOLDER = "Extensions"

    // Audit-4 #8: hard ceiling for a single plugin file. Real
    // .cs3 plugins are a few MB; this only stops a malicious or
    // compromised repository (or a MITM) from streaming data into
    // the cache dir until the device storage is full.
    const val MAX_PLUGIN_FILE_SIZE_BYTES: Long = 100_000_000L

    // Audit-4 #30: cap on entries per plugin list. The Compose
    // path already caps pluginLists at 10, but neither path
    // capped the entries INSIDE one list — a malicious or
    // compromised repository could serve a list with a huge
    // number of entries and blow up memory on the STB while it
    // is mapped/wrapped for display. Real repositories have at
    // most a few hundred plugins.
    const val MAX_PLUGINS_PER_LIST: Int = 1000
    val PREBUILT_REPOSITORIES: Array<RepositoryData> by lazy {
        getKey<Array<RepositoryData>>("PREBUILT_REPOSITORIES") ?: emptyArray()
    }
    private val GH_REGEX =
        Regex("^https://raw.githubusercontent.com/([A-Za-z0-9-]+)/([A-Za-z0-9_.-]+)/(.*)$")

    // Audit-4 #55: hoisted out of parseRepoUrl, which compiled
    // them (via toRegex()) on every call.
    private val REPO_URL_SCHEME_REGEX = Regex("^https?://")
    private val REPO_SHORT_SCHEME_REGEX =
        Regex("^(cloudstreamrepo://)|(https://cs\\.repo/\\??)")
    private val REPO_SHORTCODE_REGEX = Regex("^[a-zA-Z0-9!_-]+$")


    /** Returns a SHA-256 string of the file content.
     * Example: "sha256-b70462c264cb7f90fc2860a8e58d7544ce747ff347d1d11fa093623901853573" **/
    @WorkerThread
    fun sha256(file: File): String {
        val digest = MessageDigest.getInstance("SHA-256")

        file.inputStream().use { fis ->
            val buffer = ByteArray(8192)
            var read = fis.read(buffer)
            while (read != -1) {
                digest.update(buffer, 0, read)
                read = fis.read(buffer)
            }
        }
        return "sha256-" + digest.digest().joinToString("") { "%02x".format(it) }
    }

    /* Convert raw.githubusercontent.com urls to cdn.jsdelivr.net if enabled in settings */
    fun convertRawGitUrl(url: String): String {
        if (getKey<Boolean>(context!!.getString(R.string.jsdelivr_proxy_key)) != true) return url
        val match = GH_REGEX.find(url) ?: return url
        val (user, repo, rest) = match.destructured
        return "https://cdn.jsdelivr.net/gh/$user/$repo@$rest"
    }

    /**
     * Audit-4 #6: Audit-3 #11 upgraded only the repository entry
     * URL, but the manifest's plugin-list URLs and the plugin file
     * URLs inside the list were still used as-is — over plain HTTP
     * a network attacker can forge the list and its hashes
     * together, so every URL in that chain is upgraded as well.
     */
    fun upgradeToHttps(url: String): String {
        return if (url.startsWith("http://")) {
            "https://" + url.removePrefix("http://")
        } else {
            url
        }
    }

    suspend fun parseRepoUrl(url: String): String? {
        val fixedUrl = url.trim()
        return if (fixedUrl.contains(REPO_URL_SCHEME_REGEX)) {
            // Audit-3 #11: a repository serves the plugin list AND
            // the hashes used to verify plugins; over plain HTTP a
            // network attacker can forge both together, so repo
            // URLs are upgraded to HTTPS.
            upgradeToHttps(fixedUrl)
        } else if (fixedUrl.contains(REPO_SHORT_SCHEME_REGEX)) {
            fixedUrl.replace(REPO_SHORT_SCHEME_REGEX, "").let {
                return@let if (!it.contains(REPO_URL_SCHEME_REGEX))
                    "https://${it}"
                else fixedUrl
            }
        } else if (fixedUrl.matches(REPO_SHORTCODE_REGEX)) {
            safeAsync {
                if (fixedUrl.startsWith("!")) {
                    val response = app.get("https://py.md/${fixedUrl.removePrefix("!")}", allowRedirects = false)
                    val url = response.headers["Location"] ?: return@safeAsync null
                    if (url.startsWith("https://py.md/404")) return@safeAsync null
                    if (url.removeSuffix("/") == "https://py.md") return@safeAsync null
                    // Audit-4 #7: the redirect target becomes the
                    // stored repository URL; it skipped the HTTPS
                    // upgrade the direct-URL branch applies.
                    return@safeAsync upgradeToHttps(url)
                } else {
                    val response = app.get("https://cutt.ly/${fixedUrl}", allowRedirects = false)
                    val url = response.headers["Location"] ?: return@safeAsync null
                    if (url.startsWith("https://cutt.ly/404")) return@safeAsync null
                    if (url.removeSuffix("/") == "https://cutt.ly") return@safeAsync null
                    // Audit-4 #7: same upgrade as the py.md branch.
                    return@safeAsync upgradeToHttps(url)
                }
            }
        } else null
    }

    suspend fun parseRepository(url: String): Repository? {
        return safeAsync {
            // Take manifestVersion and such into account later
            app.get(convertRawGitUrl(url), cacheTime = 15, cacheUnit = TimeUnit.MINUTES)
                .parsedSafe<Repository>()
        }
    }

    private suspend fun parsePlugins(pluginUrls: String): List<SitePlugin> {
        // Take manifestVersion and such into account later
        return try {
            // Audit-4 #6: the plugin-list URL comes from inside the
            // repository manifest and was not covered by the
            // Audit-3 #11 entry-URL upgrade.
            app.get(
                convertRawGitUrl(upgradeToHttps(pluginUrls)),
                cacheTime = 15,
                cacheUnit = TimeUnit.MINUTES
            )
                // Audit-4 #30: see MAX_PLUGINS_PER_LIST.
                .parsed<Array<SitePlugin>>().take(MAX_PLUGINS_PER_LIST).toList()
        } catch (t: Throwable) {
            logError(t)
            emptyList()
        }
    }

    /**
     * Gets all plugins from repositories and pairs them with the repository url
     */
    suspend fun getRepoPlugins(repositoryData: RepositoryData): List<PluginWrapper>? {
        val repo = parseRepository(repositoryData.url) ?: return null
        val list = repo.pluginLists.amap { url ->
            parsePlugins(url).map {
                // Audit-4 #6: upgrade the plugin file URL itself;
                // it is fetched later by the download paths, which
                // use it verbatim.
                PluginWrapper(repo, repositoryData, it.copy(url = upgradeToHttps(it.url)))
            }
        }.flatten()
        return list
    }

    suspend fun downloadPluginToFile(
        context: Context,
        pluginUrl: String,
        file: File,
        expectedFileHash: String?
    ): File? {
        return safeAsync {
            val parentDir = file.parentFile ?: return@safeAsync null
            parentDir.mkdirs()

            // Prevent corrupting the plugin file if the operation fails
            val tempFile = File.createTempFile(file.name, ".tmp", context.cacheDir)

            // Audit-4 #32: every failure below (network error,
            // the Audit-4 #8 size ceiling, a hash mismatch) used
            // to leave the .tmp file behind in the cache dir,
            // leaking a partial plugin per failed attempt. The
            // body keeps its indentation; the finally removes the
            // temp file unless the move consumed it.
            var tempMoved = false
            try {
            val body = app.get(convertRawGitUrl(pluginUrl)).okhttpResponse.body

            // Audit-4 #8: bounded copy — the declared content
            // length is checked up front and the actual bytes are
            // counted while copying (the header can lie or be
            // absent). The manifest's fileSize was never enforced
            // on this path at all.
            if (body.contentLength() > MAX_PLUGIN_FILE_SIZE_BYTES) {
                throw IllegalStateException(
                    "Plugin file too large: ${body.contentLength()} bytes"
                )
            }
            body.byteStream().use { input ->
                tempFile.outputStream().use { output ->
                    val buffer = ByteArray(DEFAULT_BUFFER_SIZE)
                    var total = 0L
                    while (true) {
                        val read = input.read(buffer)
                        if (read < 0) break
                        total += read
                        if (total > MAX_PLUGIN_FILE_SIZE_BYTES) {
                            throw IllegalStateException(
                                "Plugin file too large: exceeds $MAX_PLUGIN_FILE_SIZE_BYTES bytes"
                            )
                        }
                        output.write(buffer, 0, read)
                    }
                }
            }

            if (expectedFileHash != null) {
                val downloadHash = sha256(tempFile)
                if (expectedFileHash != downloadHash) {
                    tempFile.delete()
                    throw IllegalStateException("Extension hash mismatch when validating '${file.name}'! Expected: '$expectedFileHash', got: '$downloadHash'.")
                }
            }

            // We prefer the operation to be atomic
            try {
                Files.move(
                    tempFile.toPath(),
                    file.toPath(),
                    StandardCopyOption.REPLACE_EXISTING,
                    StandardCopyOption.ATOMIC_MOVE
                )
            } catch (_: AtomicMoveNotSupportedException) {
                Files.move(
                    tempFile.toPath(),
                    file.toPath(),
                    StandardCopyOption.REPLACE_EXISTING
                )
            }
            tempMoved = true

            file
            } finally {
                // Audit-4 #32: see tempMoved above.
                if (!tempMoved) tempFile.delete()
            }
        }
    }

    fun getRepositories(): Array<RepositoryData> {
        return getKey<Array<RepositoryData>>(REPOSITORIES_KEY) ?: emptyArray()
    }

    // Don't want to read before we write in another thread
    private val repoLock = Mutex()
    suspend fun addRepository(repository: RepositoryData) {
        repoLock.withLock {
            // No duplicates, but we want the new repository instead of the old one
            var currentRepos = getRepositories()
            val index = currentRepos.indexOfFirst { it.url == repository.url }
            if(index == -1) {
                currentRepos += repository
            } else {
                /** We want to keep the ordering here, as that is the addition order */
                currentRepos[index] = repository
            }
            setKey(REPOSITORIES_KEY, currentRepos)
        }
    }

    /**
     * Also deletes downloaded repository plugins
     */
    suspend fun removeRepository(context: Context, repository: RepositoryData) {
        val extensionsDir = File(context.filesDir, ONLINE_PLUGINS_FOLDER)

        repoLock.withLock {
            val currentRepos = getKey<Array<RepositoryData>>(REPOSITORIES_KEY) ?: emptyArray()
            // No duplicates
            val newRepos = currentRepos.filter { it.url != repository.url }
            setKey(REPOSITORIES_KEY, newRepos)
        }

        val file = File(
            extensionsDir,
            getPluginSanitizedFileName(repository.url)
        )

        // Unload all plugins, not using deletePlugin since we
        // delete all data and files in deleteRepositoryData
        safe {
            file.listFiles { plugin: File ->
                unloadPlugin(plugin.absolutePath)
                false
            }
        }

        PluginManager.deleteRepositoryData(file.absolutePath)
    }
}
